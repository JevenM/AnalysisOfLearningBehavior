def _pv(v):
    """p 值展示：字符串（如 '<1e-6'）原样；数值补比较符。"""
    if v is None:
        return "—"
    if isinstance(v, str):
        return v
    try:
        return "<0.001" if float(v) < 0.001 else f"={float(v):.3f}"
    except (TypeError, ValueError):
        return str(v)


